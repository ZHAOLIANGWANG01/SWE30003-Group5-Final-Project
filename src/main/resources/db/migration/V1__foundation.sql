CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(30) NOT NULL CHECK (role IN ('CUSTOMER','OFFICE_STAFF','DELIVERY_STAFF')),
    display_name VARCHAR(120) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE delivery_staff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE delivery_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES users(id),
    submission_key VARCHAR(100) NOT NULL,
    original_payload VARCHAR(64) NOT NULL,
    customer_name VARCHAR(120) NOT NULL CHECK (CHAR_LENGTH(TRIM(customer_name)) > 0),
    customer_phone VARCHAR(40) NOT NULL CHECK (CHAR_LENGTH(TRIM(customer_phone)) > 0),
    pickup_address VARCHAR(500) NOT NULL CHECK (CHAR_LENGTH(TRIM(pickup_address)) > 0),
    delivery_address VARCHAR(500) NOT NULL CHECK (CHAR_LENGTH(TRIM(delivery_address)) > 0),
    recipient_name VARCHAR(120) NOT NULL CHECK (CHAR_LENGTH(TRIM(recipient_name)) > 0),
    recipient_phone VARCHAR(40) NOT NULL CHECK (CHAR_LENGTH(TRIM(recipient_phone)) > 0),
    status VARCHAR(30) NOT NULL CHECK (status IN ('REQUESTED','QUOTED','ACCEPTED','PICKED_UP','IN_TRANSIT','DELIVERED','CANCELLED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT uq_submission UNIQUE (customer_id, submission_key)
);
CREATE TABLE parcels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL UNIQUE REFERENCES delivery_requests(id),
    description VARCHAR(1000) NOT NULL CHECK (CHAR_LENGTH(TRIM(description)) > 0),
    handling_notes VARCHAR(2000) NOT NULL DEFAULT ''
);
CREATE TABLE delivery_quotes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES delivery_requests(id),
    amount DECIMAL(12,2) NOT NULL CHECK (amount > 0),
    pickup_at TIMESTAMP WITH TIME ZONE NOT NULL,
    delivery_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('ISSUED','ACCEPTED','DECLINED','EXPIRED')),
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (pickup_at < delivery_at)
);
CREATE TABLE staff_availability (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id BIGINT NOT NULL REFERENCES delivery_staff(id),
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('AVAILABLE','UNAVAILABLE')),
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (start_at < end_at)
);
CREATE TABLE delivery_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL UNIQUE REFERENCES delivery_requests(id),
    staff_id BIGINT NOT NULL REFERENCES delivery_staff(id),
    pickup_at TIMESTAMP WITH TIME ZONE NOT NULL,
    delivery_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (pickup_at < delivery_at)
);
CREATE TABLE schedule_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id BIGINT NOT NULL REFERENCES delivery_schedules(id),
    base_schedule_version BIGINT NOT NULL,
    proposed_pickup_at TIMESTAMP WITH TIME ZONE NOT NULL,
    proposed_delivery_at TIMESTAMP WITH TIME ZONE NOT NULL,
    decision VARCHAR(20) NOT NULL CHECK (decision IN ('PENDING','CONFIRMED','DECLINED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (proposed_pickup_at < proposed_delivery_at)
);
CREATE TABLE delivery_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES delivery_requests(id),
    type VARCHAR(30) NOT NULL CHECK (type IN ('QUOTED','QUOTE_ACCEPTED','PICKED_UP','IN_TRANSIT','DELIVERED','PICKUP_FAILED','DELIVERY_FAILED')),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_user_id BIGINT NOT NULL REFERENCES users(id),
    note VARCHAR(2000) NOT NULL DEFAULT ''
);
CREATE INDEX idx_requests_customer_status ON delivery_requests(customer_id, status, created_at);
CREATE INDEX idx_quotes_request ON delivery_quotes(request_id, id);
CREATE INDEX idx_availability_staff_time ON staff_availability(staff_id, start_at, end_at);
CREATE INDEX idx_schedules_staff_time ON delivery_schedules(staff_id, pickup_at, delivery_at);
CREATE INDEX idx_events_request_time ON delivery_events(request_id, occurred_at, id);
CREATE INDEX idx_changes_schedule ON schedule_changes(schedule_id, id);
